"""Structural host for the loft mixins.

Leaf module: it does not import ``loft.py`` or the ``blade.loft`` barrel, so the
mixins can name their ``self`` type without a typing cycle through that barrel.
``BladeGeometry`` remains the only public loft type.
"""

from __future__ import annotations

from typing import Any, Protocol

import numpy as np


class LoftGeometry(Protocol):
    """Attributes and methods the loft mixins use on ``BladeGeometry``."""

    stations: Any
    n_airfoil_points: int
    layout: Any
    web_offsets: Any
    merge_cap_and_skin: bool
    transverse: Any
    stringers: Any
    ply_drops: Any
    tip_closure: Any
    _chord: Any
    _twist: Any
    _offset: Any
    _web_x_from_pitch: Any
    _section_cache: Any
    _section_cache_size: int
    _skin: Any
    _cap: Any
    _web: Any

    def _pitch(self, z: float) -> float: ...
    def _placement_twist(self, twist_deg: float) -> float: ...
    def _span_scalar(self, table: Any, values: Any, z: float) -> float: ...
    def interpolate(self, z: float) -> Any: ...
    def oml_polyline(self, z: float) -> np.ndarray: ...
    def _layout_at(self, z: float) -> Any: ...
    def _pitch_metres_at(self, z: float) -> Any: ...
    def _web_feet_at(self, z: float) -> Any: ...
    def _web_tilts_at(self, z: float) -> Any: ...
    def _transverse_at(self, z: float) -> Any: ...
    def _stringers_at(self, z: float) -> Any: ...
    def _tip_closure_at(self, z: float) -> Any: ...
    def section_at(self, z: float) -> Any: ...
    def oml_sdf(self, meta: int = 0) -> Any: ...
    def wall_mid_sdf(self, meta: int = 0) -> Any: ...
    def wall_meta(self, table: Any = None) -> Any: ...
    def query(self, points: Any) -> dict[str, np.ndarray]: ...
    def thickness_at(self, z: Any, s: Any) -> np.ndarray: ...
    def tip_closure_thickness(self) -> float: ...
